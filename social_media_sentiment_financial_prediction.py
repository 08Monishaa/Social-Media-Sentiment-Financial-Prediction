# STEP 11: Financial Feature Engineering

combined_df = combined_df.sort_values('Date').copy()

# Daily stock returns
combined_df['Daily_Return'] = combined_df['Close'].pct_change(fill_method=None)

# Previous day's return
combined_df['Previous_Return'] = combined_df['Daily_Return'].shift(1)

# Moving averages
combined_df['MA_5'] = combined_df['Close'].rolling(window=5).mean()
combined_df['MA_10'] = combined_df['Close'].rolling(window=10).mean()

# Price volatility
combined_df['Volatility'] = combined_df['Daily_Return'].rolling(window=5).std()

# Trading volume change
combined_df['Volume_Change'] = combined_df['Volume'].pct_change(fill_method=None)

# Next day's closing price
combined_df['Next_Close'] = combined_df['Close'].shift(-1)

# Prediction target
combined_df['Target'] = np.where(
    combined_df['Next_Close'].notna(),
    (combined_df['Next_Close'] > combined_df['Close']).astype(int),
    np.nan
)

# Remove missing values
combined_df.replace([np.inf, -np.inf], np.nan, inplace=True)
combined_df.dropna(inplace=True)

